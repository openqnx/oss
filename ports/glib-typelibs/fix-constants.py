#!/usr/bin/env python3
"""fix-constants.py <target glibconfig.h> <glib source dir> <gir>...

The .gir files are generated by a native build of GLib on the build machine,
so every value GLib takes from the platform's glibconfig.h is the build
machine's. Rewrite those with the target's:
  - enum/bitfield members defined as a GLIB_SYSDEF_* macro in GLib's headers
    (G_IO_IN = GLIB_SYSDEF_POLLIN, G_SOCKET_FAMILY_IPV6 = GLIB_SYSDEF_AF_INET6,
    G_SOCKET_MSG_*): QNX's poll() and socket constants differ from Linux's;
  - <constant> elements whose C macro glibconfig.h defines as a plain
    number or string (G_MODULE_SUFFIX, GLIB_SIZEOF_*, ...).
Prints each value it changes; fails if a member it should fix is missing.
"""
import glob, os, re, sys

conf_h, srcdir, girs = sys.argv[1], sys.argv[2], sys.argv[3:]
conf = {}
for line in open(conf_h):
    m = re.match(r"#define\s+(\w+)\s+(.+?)\s*$", line)
    if m:
        conf[m.group(1)] = m.group(2)

def num(v):
    v = v.lstrip("=").strip().strip("()").rstrip("uUlL")
    try:
        return str(int(v, 0))
    except ValueError:
        return None

# enum members spelled with a GLIB_SYSDEF_ macro in GLib's public headers
members = {}
for h in glob.glob(os.path.join(srcdir, "g*", "*.h")):
    for m in re.finditer(r"\b(G_[A-Z0-9_]+)\s*=?\s*(GLIB_SYSDEF_[A-Z0-9_]+)", open(h, errors="replace").read()):
        members[m.group(1)] = m.group(2)
want = {}
for ident, macro in members.items():
    v = num(conf.get(macro, ""))
    if v is None:
        sys.exit("fix-constants: %s (%s) not a number in %s" % (macro, ident, conf_h))
    want[ident] = v

seen = set()
for g in girs:
    text = open(g).read()
    def fix_member(m):
        tag = m.group(0)
        ident = re.search(r'c:identifier="([^"]+)"', tag)
        if not ident or ident.group(1) not in want:
            return tag
        i = ident.group(1); seen.add(i)
        old = re.search(r'\bvalue="([^"]*)"', tag).group(1)
        if old != want[i]:
            print("%s: %s %s -> %s" % (os.path.basename(g), i, old, want[i]))
        return re.sub(r'\bvalue="[^"]*"', 'value="%s"' % want[i], tag)
    text = re.sub(r"<member\b[^>]*>", fix_member, text)
    def fix_const(m):
        tag = m.group(0)
        ct = re.search(r'c:type="([^"]+)"', tag)
        if not ct or ct.group(1) not in conf:
            return tag
        raw = conf[ct.group(1)].strip()
        new = num(raw)
        if new is None:
            s = re.fullmatch(r'"([^"\\]*)"', raw)
            if not s:
                return tag
            new = s.group(1)
        old = re.search(r'\bvalue="([^"]*)"', tag).group(1)
        if old != new:
            print("%s: constant %s %s -> %s" % (os.path.basename(g), ct.group(1), old, new))
        return re.sub(r'\bvalue="[^"]*"', 'value="%s"' % new, tag)
    text = re.sub(r"<constant\b[^>]*>", fix_const, text)
    open(g, "w").write(text)
missing = set(want) - seen
if missing:
    sys.exit("fix-constants: not found in the GIR files: " + " ".join(sorted(missing)))
