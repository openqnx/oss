# xfce4-dev-tools: what Xfce modules bootstrap and build with -- the XDT_*
# autoconf macros (XDT_CHECK_PACKAGE, XDT_FEATURE_DEBUG, XDT_I18N, ...),
# xdt-autogen (the autogen.sh of every Xfce module), xdt-csource (data to
# C arrays, GLib), xdt-gen-visibility and xdt-check-abi (Python). Version
# as in QNX's own package list.
VERSION=4.21.0
TARBALL=https://archive.xfce.org/src/xfce/xfce4-dev-tools/4.21/xfce4-dev-tools-4.21.0.tar.bz2
SHA256=36059f48bbb196645f6514ab5a356e55cdd9bc917edcaf6afd86adfc28d7a358
# glib: xdt-csource.
DEPS="glib"
# xdt-autogen requires make and runs autoreconf/aclocal/automake (and
# intltoolize, glib-gettextize or gtkdocize when a project uses them);
# xdt-gen-visibility and xdt-check-abi are Python scripts.
RUNTIME_DEPS="autoconf automake make python3"
BUILDSYS=autotools
# Everything but tests/: its test data is generated by running the
# xdt-csource just built (a QNX program) on the build machine.
XDT_SUBDIRS="docs helpers m4macros scripts xdt-csource"
do_build() { make -C "$B" -j"$(nproc)" SUBDIRS="$XDT_SUBDIRS"; }
# xdt-check-abi and xfce-build start with #!/bin/bash (the others with
# #!/usr/bin/env bash / python3): a QNX target's bash is the bash port's.
do_install() {
  make -C "$B" DESTDIR="$STAGE" SUBDIRS="$XDT_SUBDIRS" install || return 1
  sed -i "1s|^#!/bin/bash|#!$PREFIX/bin/bash|" "$STAGE$PREFIX/bin/xdt-check-abi" "$STAGE$PREFIX/bin/xfce-build"
}
