#!/bin/bash
# Build native (build-machine) tools that cross builds need to *run*.
# gettext is the recurring one: GLib, GStreamer and most of GNOME invoke
# xgettext/msgfmt during the build, and the copies in stage/ are QNX binaries.
set -o pipefail
WS="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
HT="$WS/hosttools"
mkdir -p "$HT" "$HT/bin" "$WS/logs"

# Native pkg-config wrapper, referenced by toolchain/meson-native.ini.
#
# env.sh exports PKG_CONFIG_SYSROOT_DIR pointing at the QNX staging tree, which
# is right for cross lookups and wrong for build-machine ones: it would prefix
# every native -I and -L with the QNX tree. Drop just that.
#
# PKG_CONFIG_LIBDIR must be left alone. Meson sets it itself, per machine, from
# the native file's pkg_config_libdir -- so unsetting it here threw away the
# very search path the native file provides, and wayland then found the host's
# wayland-scanner 1.20.0 instead of the 1.23.1 in hosttools, failing on the
# version check.
if [ ! -x "$HT/bin/pkg-config-native" ]; then
  echo "== installing native pkg-config wrapper -> $HT/bin/pkg-config-native"
  real=$(command -v pkg-config) || { echo "!! pkg-config not installed on this host"; exit 1; }
  cat > "$HT/bin/pkg-config-native" <<EOF
#!/bin/sh
# Generated by scripts/build-host-tools.sh -- native (build machine) lookups.
unset PKG_CONFIG_SYSROOT_DIR
exec $real "\$@"
EOF
  chmod 755 "$HT/bin/pkg-config-native"
fi

if [ ! -x "$HT/bin/xgettext" ]; then
  echo "== building native gettext -> $HT"
  # Fetch our own copy rather than requiring the gettext recipe to have run
  # first. Two reasons: the README tells you to run this script before building
  # anything, which then failed; and borrowing src/gettext would make this
  # script the first writer of a path the recipe owns -- exactly the collision
  # that silently skipped wayland's patch.
  src="$WS/src/gettext-host"
  if [ ! -d "$src" ]; then
    url=https://ftp.gnu.org/gnu/gettext/gettext-0.22.5.tar.gz   # same as ports/gettext
    mkdir -p "$src" "$WS/dist"
    tb="$WS/dist/$(basename "$url")"
    [ -f "$tb" ] || curl -fsSL --retry 3 -o "$tb" "$url" \
      || { echo "!! could not download $url"; rm -rf "$src"; exit 1; }
    tar xf "$tb" -C "$src" --strip-components=1 \
      || { echo "!! could not unpack $tb"; rm -rf "$src"; exit 1; }
  fi
  b="$WS/build/host/gettext"; rm -rf "$b"; mkdir -p "$b"
  ( cd "$b" && "$src/configure" --prefix="$HT" \
      --disable-shared --enable-static --disable-java --disable-csharp \
      --disable-nls --without-emacs --disable-openmp --with-included-libxml \
    && make -j"$(nproc)" && make install ) > "$WS/logs/hosttools-gettext.log" 2>&1 \
    || { echo "!! native gettext failed -- see $WS/logs/hosttools-gettext.log"; exit 1; }
fi
# nasm: the x86_64 assembly in dav1d, openh264, libvpx, aom and FFmpeg itself is
# NASM syntax. Without it those builds either fail outright or fall back to slow
# C paths. It is a small native autotools build.
if [ ! -x "$HT/bin/nasm" ]; then
  echo "== building native nasm -> $HT"
  src="$WS/src/nasm-host"
  [ -d "$src" ] || git clone -q --depth 1 -b nasm-2.16.03 https://github.com/netwide-assembler/nasm.git "$src"
  # nasm's generated sources land in x86/ and its out-of-tree build does not
  # create that directory, so build in-tree.
  ( cd "$src" && [ -x ./configure ] || ./autogen.sh ) >> "$WS/logs/hosttools-nasm.log" 2>&1
  ( cd "$src" && ./configure --prefix="$HT" \
    && make -j"$(nproc)" nasm ndisasm && install -m755 nasm ndisasm "$HT/bin/" ) \
    >> "$WS/logs/hosttools-nasm.log" 2>&1 \
    || { echo "!! native nasm failed -- see $WS/logs/hosttools-nasm.log"; exit 1; }
fi

# wayland-scanner turns Wayland's XML protocol definitions into C during the
# build, so it has to be a build-machine binary. Build just the scanner.
# The same version as the wayland port (wayland.pc and wayland-scanner.pc
# report the port's version, and wlroots checks the scanner's against it).
WL_VER=$(sed -n 's/^VERSION=\([^;]*\).*/\1/p' "$WS/ports/wayland/recipe.sh")
if [ "$("$HT/bin/wayland-scanner" --version 2>&1 | grep -Eo '[0-9][0-9.]+$')" != "$WL_VER" ]; then
  echo "== building native wayland-scanner $WL_VER -> $HT"
  # src/wayland-host, NOT src/wayland: that path belongs to the wayland recipe.
  # Cloning into it made the recipe's fetch a no-op -- and the driver applies
  # patches only on first fetch -- so 0001-qnx-peercred-and-memstream.patch was
  # silently skipped and the cross build died on
  # "Don't know how to read ucred on this platform". Every other host tool here
  # already uses its own -host/-native directory; this one was the exception.
  src="$WS/src/wayland-host"
  [ "$(git -C "$src" describe --tags 2>/dev/null)" = "$WL_VER" ] || { rm -rf "$src"; git clone -q --depth 1 -b "$WL_VER" \
      https://gitlab.freedesktop.org/wayland/wayland.git "$src"; }
  b="$WS/build/host/wayland"; rm -rf "$b"
  ( unset CC CXX CPP CFLAGS CXXFLAGS CPPFLAGS LDFLAGS PKG_CONFIG_LIBDIR PKG_CONFIG_SYSROOT_DIR
    meson setup "$b" "$src" --prefix="$HT" \
      -Dtests=false -Ddocumentation=false -Ddtd_validation=false \
      -Dscanner=true -Dlibraries=false \
    && ninja -C "$b" && ninja -C "$b" install ) > "$WS/logs/hosttools-wayland.log" 2>&1 \
    || { echo "!! native wayland-scanner failed -- see $WS/logs/hosttools-wayland.log"; exit 1; }
fi

# libthai generates its word-break dictionary at build time by running
# trietool, which libdatrie installs. The cross-built copy is a QNX binary and
# cannot run here, so build a native libdatrie just for the tool.
if [ ! -x "$HT/bin/trietool" ]; then
  echo "== building native trietool (libdatrie) -> $HT"
  src="$WS/src/libdatrie-native"
  [ -d "$src" ] || git clone -q --depth 1 -b v0.2.13 \
      https://github.com/tlwg/libdatrie.git "$src"
  aux=$(ls -d /usr/share/automake-*/ 2>/dev/null | head -1)
  mkdir -p "$src/build-aux"
  for f in config.guess config.sub compile missing install-sh depcomp ar-lib; do
    [ -e "$aux/$f" ] && cp -f "$aux/$f" "$src/build-aux/$f"
  done
  chmod u+x "$src/build-aux/"* 2>/dev/null
  # Same AX_COMPARE_VERSION problem as the cross build: the macro comes from
  # autoconf-archive, which is not installed, so autoreconf refuses. Apply the
  # recipe's patch here too.
  ( cd "$src" && patch -p1 -N -r - < "$WS/ports/libdatrie/patches/0001-drop-ax-compare-version.patch" ) >/dev/null 2>&1
  b="$WS/build/host/libdatrie"; rm -rf "$b"; mkdir -p "$b"
  ( unset CC CXX CPP CFLAGS CXXFLAGS CPPFLAGS LDFLAGS PKG_CONFIG_LIBDIR PKG_CONFIG_SYSROOT_DIR
    cd "$src" && autoreconf -fi \
    && cd "$b" && "$src/configure" --prefix="$HT" --disable-doxygen-doc --disable-shared \
    && make -j"$(nproc)" && make install ) > "$WS/logs/hosttools-libdatrie.log" 2>&1 \
    || { echo "!! native trietool failed -- see $WS/logs/hosttools-libdatrie.log"; exit 1; }
fi

# Cross-building CPython needs a native interpreter of the *same* version: the
# build freezes its own stdlib modules and runs configure-time helpers with it,
# and --with-build-python rejects a version mismatch. The distribution's python3
# is a different release, so build 3.14 here.
if [ ! -x "$HT/bin/python3.14" ]; then
  echo "== building native CPython 3.14 -> $HT"
  tb="$WS/dist/Python-3.14.0.tar.xz"
  [ -f "$tb" ] || curl -fsSL --retry 3 -o "$tb" \
      https://www.python.org/ftp/python/3.14.0/Python-3.14.0.tar.xz
  src="$WS/src/python-native"
  [ -d "$src" ] || { mkdir -p "$src"; tar xf "$tb" -C "$src" --strip-components=1; }
  b="$WS/build/host/python"; rm -rf "$b"; mkdir -p "$b"
  ( unset CC CXX CPP CFLAGS CXXFLAGS CPPFLAGS LDFLAGS PKG_CONFIG_LIBDIR PKG_CONFIG_SYSROOT_DIR
    cd "$b" && "$src/configure" --prefix="$HT" --without-ensurepip \
      --disable-test-modules --with-ensurepip=no \
    && make -j"$(nproc)" && make install ) > "$WS/logs/hosttools-python.log" 2>&1 \
    || { echo "!! native CPython failed -- see $WS/logs/hosttools-python.log"; exit 1; }
fi

# Every X.Org library's configure.ac starts with XORG_MACROS_VERSION, so
# autoreconf refuses without util-macros installed on the *build* machine:
# "must install xorg-macros 1.8 or later". It ships only m4 macros -- no code.
if [ ! -f "$HT/share/aclocal/xorg-macros.m4" ]; then
  echo "== installing xorg util-macros -> $HT"
  src="$WS/src/xorg-macros"
  [ -d "$src" ] || git clone -q --depth 1 -b util-macros-1.20.1 \
      https://gitlab.freedesktop.org/xorg/util/macros.git "$src"
  b="$WS/build/host/xorg-macros"; rm -rf "$b"; mkdir -p "$b"
  ( unset CC CXX CPP CFLAGS CXXFLAGS CPPFLAGS LDFLAGS PKG_CONFIG_LIBDIR PKG_CONFIG_SYSROOT_DIR
    cd "$src" && autoreconf -fi \
    && cd "$b" && "$src/configure" --prefix="$HT" && make install ) \
    > "$WS/logs/hosttools-xorg-macros.log" 2>&1 \
    || { echo "!! xorg util-macros failed -- see $WS/logs/hosttools-xorg-macros.log"; exit 1; }
fi

# GTK_DOC_CHECK comes from gtk-doc, which is a documentation toolchain we do not
# want and cannot usefully cross-build. Without the macro, autoconf leaves the
# call unexpanded and the generated configure dies in the *shell*:
# "syntax error near unexpected token `1.12'". Install a stub that declares the
# same substitutions and conditionals with documentation switched off, so any
# package including it configures cleanly.
if [ ! -f "$HT/share/aclocal/gtk-doc.m4" ]; then
  echo "== installing gtk-doc.m4 stub -> $HT"
  mkdir -p "$HT/share/aclocal"
  cat > "$HT/share/aclocal/gtk-doc.m4" <<'M4'
dnl Stub for GTK_DOC_CHECK: documentation is disabled in this workspace.
dnl It declares exactly what a package's Makefile.am expects to exist.
AC_DEFUN([GTK_DOC_CHECK],
[
  AC_ARG_WITH([html-dir],
    AS_HELP_STRING([--with-html-dir=PATH], [path to installed docs]),,
    [with_html_dir='${datadir}/gtk-doc/html'])
  HTML_DIR="$with_html_dir"
  AC_SUBST([HTML_DIR])
  AC_ARG_ENABLE([gtk-doc],
    AS_HELP_STRING([--enable-gtk-doc], [use gtk-doc to build documentation]),,
    [enable_gtk_doc=no])
  AC_ARG_ENABLE([gtk-doc-html],
    AS_HELP_STRING([--enable-gtk-doc-html], [build documentation in html format]),,
    [enable_gtk_doc_html=no])
  AC_ARG_ENABLE([gtk-doc-pdf],
    AS_HELP_STRING([--enable-gtk-doc-pdf], [build documentation in pdf format]),,
    [enable_gtk_doc_pdf=no])
  GTKDOC_DEPS_CFLAGS=""; GTKDOC_DEPS_LIBS=""
  AC_SUBST([GTKDOC_DEPS_CFLAGS])
  AC_SUBST([GTKDOC_DEPS_LIBS])
  AM_CONDITIONAL([ENABLE_GTK_DOC], [false])
  AM_CONDITIONAL([GTK_DOC_BUILD_HTML], [false])
  AM_CONDITIONAL([GTK_DOC_BUILD_PDF], [false])
  AM_CONDITIONAL([GTK_DOC_USE_LIBTOOL], [false])
  AM_CONDITIONAL([GTK_DOC_USE_REBASE], [false])
])
AC_DEFUN([GTK_DOC_USE_LIBTOOL], [])
M4
fi

# autoreconf runs "gtkdocize" itself when configure.ac calls GTK_DOC_CHECK, and
# fails outright if the program is missing -- the m4 stub above is not enough on
# its own. gtkdocize's whole job is to copy gtk-doc.make next to configure.ac,
# so a stub that writes the disabled-documentation version is a faithful
# substitute for a build that wants no documentation.
if [ ! -x "$HT/bin/gtkdocize" ]; then
  echo "== installing gtkdocize stub -> $HT"
  mkdir -p "$HT/bin"
  cat > "$HT/bin/gtkdocize" <<'SH'
#!/bin/sh
# Stub gtkdocize: drop in a gtk-doc.make that declares the variables a
# package's doc/Makefile.am appends to, with documentation disabled.
dir=.
while [ $# -gt 0 ]; do
  case "$1" in
    --srcdir) dir="$2"; shift 2 ;;
    --srcdir=*) dir="${1#--srcdir=}"; shift ;;
    --copy|--flavour|--flavour=*|--docdir|--docdir=*) shift ;;
    *) shift ;;
  esac
done
cat > "$dir/gtk-doc.make" <<'MK'
# Generated by the gtkdocize stub: documentation is disabled.
CLEANFILES =
EXTRA_DIST =
GTKDOC_CC =
GTKDOC_LD =
GTKDOC_RUN =
.PHONY: docs
docs:
MK
exit 0
SH
  chmod +x "$HT/bin/gtkdocize"
fi

# The Xfce libraries run xdt-gen-visibility during the build to generate their
# symbol-visibility headers. It ships in xfce4-dev-tools and is a build-machine
# script, so a cross-built copy would be useless even if one existed.
if [ ! -x "$HT/bin/xdt-gen-visibility" ]; then
  echo "== installing xfce4-dev-tools (xdt-gen-visibility) -> $HT"
  src="$WS/src/xfce4-dev-tools"
  [ -d "$src" ] || git clone -q --depth 1 -b xfce4-dev-tools-4.20.0 \
      https://gitlab.xfce.org/xfce/xfce4-dev-tools.git "$src"
  # The package is autotools and builds a lot we do not need; the generator is a
  # standalone script, so install just that.
  install -m 755 "$src/scripts/xdt-gen-visibility" "$HT/bin/xdt-gen-visibility" \
    || { echo "!! xdt-gen-visibility not found in $src/scripts"; exit 1; }
  # The XDT_* macros its packages call at autoreconf time ship in the same
  # package; without them autoreconf stops with "Please install the
  # xfce4-dev-tools package first".
  mkdir -p "$HT/share/aclocal"
  install -m 644 "$src"/m4macros/*.m4 "$HT/share/aclocal/"
fi

# WebKit's build runs ruby, gperf and unifdef on the build machine: ruby drives
# the bindings and builtins generators (JavaScriptCore's DerivedSources), gperf
# builds the HTML/CSS/SVG perfect-hash tables, unifdef trims the installed
# headers.  None of them are on this host and there is no root to install them.
if [ ! -x "$HT/bin/gperf" ]; then
  echo "== building native gperf -> $HT"
  src="$WS/src/gperf-host"
  if [ ! -d "$src" ]; then
    mkdir -p "$src"
    curl -fsSL --retry 3 -o "$WS/dist/gperf-3.1.tar.gz" https://ftp.gnu.org/pub/gnu/gperf/gperf-3.1.tar.gz       && tar xf "$WS/dist/gperf-3.1.tar.gz" -C "$src" --strip-components=1
  fi
  b="$WS/build/host/gperf"; rm -rf "$b"; mkdir -p "$b"
  ( cd "$b" && "$src/configure" --prefix="$HT" && make -j"$(nproc)" && make install )     > "$WS/logs/hosttools-gperf.log" 2>&1     || { echo "!! native gperf failed -- see $WS/logs/hosttools-gperf.log"; exit 1; }
fi

# GNU ed is published only as .tar.lz: tar needs lzip on the build machine.
if [ ! -x "$HT/bin/lzip" ]; then
  echo "== building native lzip -> $HT"
  src="$WS/src/lzip-host"
  if [ ! -d "$src" ]; then
    mkdir -p "$src"
    curl -fsSL --retry 3 -o "$WS/dist/lzip-1.26.tar.gz" https://download.savannah.gnu.org/releases/lzip/lzip-1.26.tar.gz \
      && tar xf "$WS/dist/lzip-1.26.tar.gz" -C "$src" --strip-components=1
  fi
  ( cd "$src" && ./configure --prefix="$HT" CXX=g++ && make -j"$(nproc)" && make install ) > "$WS/logs/hosttools-lzip.log" 2>&1 \
    || { echo "!! native lzip failed -- see $WS/logs/hosttools-lzip.log"; exit 1; }
fi

if [ ! -x "$HT/bin/unifdef" ]; then
  echo "== building native unifdef -> $HT"
  src="$WS/src/unifdef-host"
  [ -d "$src" ] || git clone -q --depth 1 -b unifdef-2.12 https://github.com/fanf2/unifdef.git "$src"
  ( cd "$src" && make -j"$(nproc)" unifdef && install -m 755 unifdef "$HT/bin/unifdef" )     > "$WS/logs/hosttools-unifdef.log" 2>&1     || { echo "!! native unifdef failed -- see $WS/logs/hosttools-unifdef.log"; exit 1; }
fi

# Ruby's YAML module (psych) is a C extension over libyaml; without it, ruby
# builds happily and then every WebKit generator that reads a .yaml dies with
# "cannot load such file -- psych".  Build libyaml first and point ruby at it.
if [ ! -f "$HT/include/yaml.h" ]; then
  echo "== building native libyaml -> $HT"
  src="$WS/src/libyaml-host"
  [ -d "$src" ] || git clone -q --depth 1 -b 0.2.5 https://github.com/yaml/libyaml.git "$src"
  b="$WS/build/host/libyaml"; rm -rf "$b"; mkdir -p "$b"
  ( cd "$src" && [ -x ./configure ] || ./bootstrap ) > "$WS/logs/hosttools-libyaml.log" 2>&1
  ( cd "$b" && "$src/configure" --prefix="$HT" --enable-static && make -j"$(nproc)" && make install ) \
    >> "$WS/logs/hosttools-libyaml.log" 2>&1 \
    || { echo "!! native libyaml failed -- see $WS/logs/hosttools-libyaml.log"; exit 1; }
fi

if [ ! -x "$HT/bin/ruby" ]; then
  echo "== building native ruby -> $HT   (this one takes a while)"
  src="$WS/src/ruby-host"
  if [ ! -d "$src" ]; then
    mkdir -p "$src"
    curl -fsSL --retry 3 -o "$WS/dist/ruby-3.3.6.tar.gz"       https://cache.ruby-lang.org/pub/ruby/3.3/ruby-3.3.6.tar.gz       && tar xf "$WS/dist/ruby-3.3.6.tar.gz" -C "$src" --strip-components=1
  fi
  b="$WS/build/host/ruby"; rm -rf "$b"; mkdir -p "$b"
  # Only the interpreter is needed, and only to run WebKit's generators.
  # --with-opt-dir: where psych's extconf looks for yaml.h and libyaml.  Passing
  # CPPFLAGS/LDFLAGS or --with-libyaml-dir does not reach the extension build.
  ( cd "$b" && "$src/configure" --prefix="$HT" --disable-install-doc \
      --disable-install-rdoc --without-gmp --disable-shared \
      --with-opt-dir="$HT" \
    && make -j"$(nproc)" && make install ) > "$WS/logs/hosttools-ruby.log" 2>&1 \
    || { echo "!! native ruby failed -- see $WS/logs/hosttools-ruby.log"; exit 1; }
fi

echo "host tools ready: $(ls "$HT/bin" | tr '\n' ' ')"
