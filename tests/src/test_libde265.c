static uint8_t expect_sample(int c, int x, int y, int k) {
  if (c == 0) return (uint8_t)((x * 3 + y * 2 + 16 * k) & 255);
  return (uint8_t)(c == 1 ? 96 + 8 * k : 160 - 8 * k);
}
static int run(const char *cmd, char *out, size_t n) {
  out[0] = 0;
  FILE *p = popen(cmd, "r");
  if (!p) return -1;
  size_t len = fread(out, 1, n - 1, p);
  out[len] = 0;
  int st = pclose(p);
  return WIFEXITED(st) ? WEXITSTATUS(st) : -1;
}

int main(void) {
  QT_BEGIN("libde265");
  const char *ver = de265_get_version();
  printf("  info libde265 %s\n", ver ? ver : "(null)");
  QT_CHECK(de265_get_version_number_major() == 1 && de265_get_version_number_minor() == 0,
           "de265_get_version_number: 1.0.x");
  de265_init();
  de265_decoder_context *ctx = de265_new_decoder();
  QT_CHECK(ctx != NULL, "de265_new_decoder");
  if (!ctx) QT_END();
  de265_set_parameter_bool(ctx, DE265_DECODER_PARAM_BOOL_SEI_CHECK_HASH, 1);
  de265_error err = de265_push_data(ctx, stream, sizeof stream, 0, NULL);
  QT_CHECK(de265_isOK(err), "de265_push_data");
  de265_flush_data(ctx);

  int frames = 0, mismatches = 0, geometry_ok = 1, hash_errors = 0, more = 1, loops = 0;
  while (more && loops++ < 10000) {
    more = 0;
    err = de265_decode(ctx, &more);
    if (err == DE265_ERROR_CHECKSUM_MISMATCH) hash_errors++;
    else if (!de265_isOK(err) && err != DE265_ERROR_WAITING_FOR_INPUT_DATA) {
      printf("  info de265_decode: %s\n", de265_get_error_text(err));
      break;
    }
    for (de265_error w; (w = de265_get_warning(ctx)) != DE265_OK;) {
      if (w == DE265_ERROR_CHECKSUM_MISMATCH) hash_errors++;
      printf("  info warning: %s\n", de265_get_error_text(w));
    }
    const struct de265_image *img;
    while ((img = de265_get_next_picture(ctx)) != NULL) {
      if (de265_get_image_width(img, 0) != W || de265_get_image_height(img, 0) != H ||
          de265_get_image_width(img, 1) != W / 2 || de265_get_chroma_format(img) != de265_chroma_420 ||
          de265_get_bits_per_pixel(img, 0) != 8)
        geometry_ok = 0;
      for (int c = 0; c < 3; c++) {
        int stride = 0, cw = c ? W / 2 : W, ch = c ? H / 2 : H;
        const uint8_t *p = de265_get_image_plane(img, c, &stride);
        for (int y = 0; p && y < ch; y++)
          for (int x = 0; x < cw; x++)
            if (p[y * stride + x] != expect_sample(c, x, y, frames)) {
              if (mismatches++ < 3)
                printf("  info frame %d plane %d (%d,%d): %d, want %d\n", frames, c, x, y,
                       p[y * stride + x], expect_sample(c, x, y, frames));
            }
      }
      frames++;
    }
  }
  printf("  info decoded %d frame(s), %d sample mismatch(es), %d hash error(s)\n", frames,
         mismatches, hash_errors);
  QT_CHECK(frames == NFRAMES, "3 pictures decoded");
  QT_CHECK(geometry_ok, "32x32 8-bit 4:2:0 pictures");
  QT_CHECK(frames > 0 && mismatches == 0, "every sample equals the generating formula (lossless)");
  QT_CHECK(hash_errors == 0, "SEI MD5 picture hashes verified");
  de265_free_decoder(ctx);

  /* A truncated stream must not produce the full set of pictures or crash. */
  ctx = de265_new_decoder();
  de265_push_data(ctx, stream, 40, 0, NULL);
  de265_flush_data(ctx);
  int tframes = 0;
  more = 1; loops = 0;
  while (more && loops++ < 1000) {
    more = 0;
    err = de265_decode(ctx, &more);
    if (!de265_isOK(err) && err != DE265_ERROR_WAITING_FOR_INPUT_DATA) break;
    while (de265_get_next_picture(ctx)) tframes++;
  }
  QT_CHECK(tframes == 0, "a stream cut inside the headers yields no pictures");
  de265_free_decoder(ctx);
  de265_free();

  /* dec265 on the same stream, reconstruction compared byte for byte. */
  char dir[] = "/tmp/qnxport-de265.XXXXXX", path[256], cmd[512], out[4096];
  QT_CHECK(mkdtemp(dir) != NULL, "scratch directory");
  snprintf(path, sizeof path, "%s/in.h265", dir);
  FILE *f = fopen(path, "wb");
  if (f) { fwrite(stream, 1, sizeof stream, f); fclose(f); }
  snprintf(cmd, sizeof cmd, "cd %s && dec265 -q -c -t 0 -o out.yuv in.h265 2>&1", dir);
  int rc = run(cmd, out, sizeof out);
  printf("  info dec265 rc=%d: %.300s\n", rc, out);
  QT_CHECK(rc == 0, "dec265 -q -c exits 0");
  QT_CHECK(strstr(out, "MD5") == NULL || strstr(out, "mismatch") == NULL, "dec265 reports no hash mismatch");
  snprintf(path, sizeof path, "%s/out.yuv", dir);
  static uint8_t yuv[NFRAMES * W * H * 3 / 2 + 16];
  size_t got = 0;
  f = fopen(path, "rb");
  if (f) { got = fread(yuv, 1, sizeof yuv, f); fclose(f); }
  int bad = got != NFRAMES * W * H * 3 / 2;
  for (int k = 0; !bad && k < NFRAMES; k++) {
    const uint8_t *fr = yuv + k * W * H * 3 / 2;
    for (int y = 0; y < H; y++) for (int x = 0; x < W; x++) bad |= fr[y * W + x] != expect_sample(0, x, y, k);
    for (int i = 0; i < W * H / 4; i++) bad |= fr[W * H + i] != expect_sample(1, 0, 0, k) ||
                                               fr[W * H * 5 / 4 + i] != expect_sample(2, 0, 0, k);
  }
  printf("  info out.yuv: %zu bytes\n", got);
  QT_CHECK(!bad, "dec265 -o: 4608 bytes, identical to the source frames");
  snprintf(cmd, sizeof cmd, "rm -rf %s", dir);
  if (system(cmd) != 0) printf("  info could not remove %s\n", dir);
  QT_END();
}
