static unsigned char hashed[2048];
static size_t hashed_len;
static void hash_cb(void *arg, const void *buf, size_t len) {
  (void)arg;
  if (hashed_len + len <= sizeof hashed) memcpy(hashed + hashed_len, buf, len);
  hashed_len += len;
}

int main(void) {
  QT_BEGIN("libksba");
  const char *v = ksba_check_version(NULL);
  printf("  info ksba_check_version: %s\n", v ? v : "(null)");
  QT_CHECK(v && strcmp(v, "1.8.1") == 0, "library version 1.8.1");

  ksba_cert_t cert = NULL;
  QT_CHECK(ksba_cert_new(&cert) == 0, "ksba_cert_new");
  gpg_error_t err = ksba_cert_init_from_mem(cert, cert_der, sizeof cert_der);
  QT_CHECK(err == 0, "certificate (444 bytes DER) parsed");
  if (err) { printf("  info error: %s\n", gpg_strerror(err)); QT_END(); }

  char *s = ksba_cert_get_subject(cert, 0);
  printf("  info subject: %s\n", s ? s : "(null)");
  QT_CHECK(s && strcmp(s, "CN=ksba.test,O=QNX Port Test,C=CA") == 0, "subject DN (RFC 2253)");
  ksba_free(s);
  s = ksba_cert_get_issuer(cert, 0);
  QT_CHECK(s && strcmp(s, "CN=ksba.test,O=QNX Port Test,C=CA") == 0, "issuer DN equals subject (self-signed)");
  ksba_free(s);

  ksba_sexp_t serial = ksba_cert_get_serial(cert);
  QT_CHECK(serial && memcmp(serial, "(4:\x12\x34\xab\xcd)", 8) == 0, "serial number 0x1234ABCD");
  ksba_free(serial);

  ksba_isotime_t t;
  QT_CHECK(ksba_cert_get_validity(cert, 0, t) == 0 && strcmp(t, "20261031T230532") == 0, "notBefore 20261031T230532");
  QT_CHECK(ksba_cert_get_validity(cert, 1, t) == 0 && strcmp(t, "20361028T230532") == 0, "notAfter 20361028T230532");

  const char *algo = ksba_cert_get_digest_algo(cert);
  printf("  info signature algorithm: %s\n", algo ? algo : "(null)");
  QT_CHECK(algo && strcmp(algo, "1.2.840.10045.4.3.2") == 0, "signature algorithm ecdsa-with-SHA256");

  ksba_sexp_t pk = ksba_cert_get_public_key(cert);
  QT_CHECK(pk && strstr((const char *)pk, "3:ecc") && strstr((const char *)pk, "1:q65:\x04"),
           "public key is an ECC point (65-byte uncompressed q)");
  ksba_free(pk);

  hashed_len = 0;
  QT_CHECK(ksba_cert_hash(cert, 0, hash_cb, NULL) == 0 && hashed_len == sizeof cert_der
           && memcmp(hashed, cert_der, sizeof cert_der) == 0, "hash callback receives the exact 444-byte DER image");
  int ca = -1, pathlen = -1;
  err = ksba_cert_is_ca(cert, &ca, &pathlen);
  printf("  info is_ca: err=%u ca=%d\n", err, ca);
  QT_CHECK(err == 0 && ca == 1, "basicConstraints: CA (openssl req -x509 default)");
  ksba_cert_release(cert);

  unsigned char *der = NULL; size_t derlen = 0;
  QT_CHECK(ksba_oid_from_str("1.2.840.113549.1.1.11", &der, &derlen) == 0 && derlen == 9
           && memcmp(der, "\x2a\x86\x48\x86\xf7\x0d\x01\x01\x0b", 9) == 0, "OID 1.2.840.113549.1.1.11 -> DER 2a864886f70d01010b");
  char *oid = ksba_oid_to_str((const char *)der, derlen);
  QT_CHECK(oid && strcmp(oid, "1.2.840.113549.1.1.11") == 0, "DER -> OID string round trip");
  ksba_free(oid); ksba_free(der);

  QT_CHECK(ksba_dn_teststr("CN=Foo,O=Bar", 0, NULL, NULL) == 0, "DN \"CN=Foo,O=Bar\" is valid");
  unsigned char *dn = NULL; size_t dnlen = 0;
  err = ksba_dn_str2der("CN=Foo", &dn, &dnlen);
  /* SEQUENCE { SET { SEQUENCE { OID 2.5.4.3, PrintableString "Foo" } } } */
  static const unsigned char want[] = { 0x30,0x0e,0x31,0x0c,0x30,0x0a,0x06,0x03,0x55,0x04,0x03,0x13,0x03,'F','o','o' };
  QT_CHECK(err == 0 && dnlen == sizeof want && memcmp(dn, want, sizeof want) == 0, "DN \"CN=Foo\" -> 16-byte DER");
  ksba_free(dn);
  QT_END();
}
