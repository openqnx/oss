#!/bin/sh
# openresolv in a scratch root: the installed resolvconf and its
# subscribers (libexec/resolvconf), copied with their configuration
# directory (SYSCONFDIR, LIBEXECDIR -- compiled into each script) pointed
# at a temporary directory whose resolvconf.conf sends resolv.conf, the
# state directory and an unbound include file there -- the system's
# /etc/resolv.conf is never touched (resolvconf refuses to overwrite a
# resolv.conf it did not generate, which is checked too). Checks: -a for two interfaces, the merged resolv.conf (both
# nameservers, search domains merged, the header), interface_order
# putting "tap*" first, -l listing an interface, -i listing
# interfaces, exclusive (-x) handling, -d removing one, the
# unbound subscriber writing forward-zone entries, and -u regenerating.
if [ -z "$QNXPORT_INNER" ]; then
  QNXPORT_INNER=/tmp/qnxport-out.$$; export QNXPORT_INNER
  sh "$0" "$@" > "$QNXPORT_INNER" 2>&1 < /dev/null &
  qp=$!; qi=0
  while kill -0 $qp 2>/dev/null && [ $qi -lt 170 ]; do sleep 1; qi=$((qi+1)); done
  if kill -0 $qp 2>/dev/null; then
    kill $qp 2>/dev/null; sleep 1; kill -KILL $qp 2>/dev/null
    cat "$QNXPORT_INNER"; echo "  FAIL watchdog: still running after 170 s -- stopped"
    echo "FAIL ${0##*/} (watchdog)"; rm -f "$QNXPORT_INNER"; exit 1
  fi
  wait $qp; rc=$?; cat "$QNXPORT_INNER"; rm -f "$QNXPORT_INNER"; exit $rc
fi
N=openresolv
echo "== $N =="
fail=0
ok() { echo "  ok   $1"; }; bad() { echo "  FAIL $1"; fail=$((fail+1)); }; info() { echo "  info $1"; }
has() { grep -q -- "$1" "$2"; }
L=/usr/local; [ -d "$L/sbin" ] || L=/data/oss/usr/local
T=$(mktemp -d /tmp/qnxport-$N.XXXXXX) && cd "$T" || { echo "FAIL $N (no temp dir)"; exit 1; }
trap 'cd /; rm -rf "$T"' EXIT
before=$(cksum /etc/resolv.conf 2>/dev/null)
# the installed scripts, SYSCONFDIR/LIBEXECDIR/the resolvconf path pointed here
mkdir etc lx
fix() { sed -e "s|^SYSCONFDIR=.*|SYSCONFDIR=$T/etc|" -e "s|^LIBEXECDIR=.*|LIBEXECDIR=$T/lx|" -e "s|$L/sbin/resolvconf|$T/rc|g" "$1" > "$2"; }
fix "$L/sbin/resolvconf" rc && chmod +x rc
(cd "$L/libexec/resolvconf" && find . -type d) | while read d; do mkdir -p "lx/$d"; done
(cd "$L/libexec/resolvconf" && find . -type f) | while read f; do fix "$L/libexec/resolvconf/$f" "lx/$f"; done
n=$(cd lx && find . -type f | wc -l | tr -d ' '); [ "$n" -ge 8 ] && ok "installed resolvconf + $n subscribers copied into the scratch root" || bad "subscribers: $n"
# unbound_restart: there is no unbound to restart here
cat > etc/resolvconf.conf <<EOS
resolv_conf=$T/resolv.conf
state_dir=$T/state
interface_order='tap* wm*'
unbound_conf=$T/unbound.conf
unbound_restart=:
EOS
r=$(./rc --version 2>&1 | head -1); info "$r"
printf 'nameserver 192.0.2.1\nsearch lan.example\n' | ./rc -a wm0 && ok "resolvconf -a wm0" || bad "-a wm0"
printf 'nameserver 198.51.100.53\ndomain vpn.example\n' | ./rc -a tap0 && ok "resolvconf -a tap0" || bad "-a tap0"
if [ -f resolv.conf ]; then
  info "resolv.conf: $(tr '\n' '|' < resolv.conf)"
  has "Generated by resolvconf" resolv.conf && ok "resolv.conf written in the scratch root, with its header" || bad "header"
  has "nameserver 192.0.2.1" resolv.conf && has "nameserver 198.51.100.53" resolv.conf && ok "both nameservers merged" || bad "nameservers"
  first=$(grep -m1 '^nameserver' resolv.conf); [ "$first" = "nameserver 198.51.100.53" ] && ok "interface_order: tap0's server first" || bad "order: $first"
  s=$(grep '^search' resolv.conf); case "$s" in *vpn.example*lan.example*) ok "search merged: $s";; *) bad "search: $s";; esac
else bad "no resolv.conf written"; fi
r=$(./rc -i | tr '\n' ' '); case "$r" in *tap0*wm0*) ok "-i lists tap0 wm0 (in order)";; *) bad "-i: $r";; esac
r=$(./rc -l wm0); case "$r" in *"192.0.2.1"*) ok "-l wm0 shows its configuration";; *) bad "-l: $r";; esac
[ -f unbound.conf ] && has 'forward-zone' unbound.conf && has 'vpn.example' unbound.conf && ok "unbound subscriber: forward-zone for vpn.example" || bad "unbound.conf: $(tr '\n' '|' < unbound.conf 2>/dev/null)"
printf 'nameserver 203.0.113.9\n' | ./rc -x -a ppp0 && ! has "192.0.2.1" resolv.conf && has "203.0.113.9" resolv.conf && ok "-x (exclusive) ppp0: only its server" || bad "exclusive: $(tr '\n' '|' < resolv.conf)"
./rc -d ppp0 && has "192.0.2.1" resolv.conf && ! has "203.0.113.9" resolv.conf && ok "-d ppp0: the others come back" || bad "-d: $(tr '\n' '|' < resolv.conf)"
./rc -d tap0 && ! has "198.51.100.53" resolv.conf && has "192.0.2.1" resolv.conf && ok "-d tap0 removes its server" || bad "-d tap0"
rm -f resolv.conf; ./rc -u && has "192.0.2.1" resolv.conf && ok "-u regenerates resolv.conf" || bad "-u"
[ "$(cksum /etc/resolv.conf 2>/dev/null)" = "$before" ] && ok "/etc/resolv.conf untouched" || bad "/etc/resolv.conf changed"
# a resolv.conf resolvconf did not generate is not overwritten
printf 'nameserver 10.0.0.1\n# written by hand\n' > foreign.conf; fsum=$(cksum < foreign.conf)
sed "s|^resolv_conf=.*|resolv_conf=$T/foreign.conf|" etc/resolvconf.conf > etc/x && mv etc/x etc/resolvconf.conf
r=$(printf 'nameserver 192.0.2.99\n' | ./rc -a wm9 2>&1)
case "$r" in *"signature mismatch"*) ok "a hand-written resolv.conf is left alone (signature mismatch)";; *) bad "foreign resolv.conf: $r";; esac
[ "$(cksum < foreign.conf)" = "$fsum" ] && ok "the hand-written file is unchanged" || bad "foreign.conf changed"
[ $fail -eq 0 ] && { echo "PASS $N"; exit 0; }
echo "FAIL $N ($fail check(s) failed)"; exit 1
