#!/bin/sh
# scdoc: renders a man page source using every construct (title line,
# sections, bold, underline, escapes, nested and numbered lists, a literal
# block, a table) with SOURCE_DATE_EPOCH=0: the roff output is identical,
# byte for byte, to the build machine's scdoc 1.11.3's (known checksum),
# with the expected .TH, font changes and table; a page without a manual
# section is an error (exit 1).
# Run the test itself in the background, its output to a log, and wait at
# most 170 s: nothing it leaves behind can hold the runner's output, and a
# hang ends as a FAIL with whatever the test printed so far.
if [ -z "$QNXPORT_INNER" ]; then
  QNXPORT_INNER=/tmp/qnxport-out.$$; export QNXPORT_INNER
  sh "$0" "$@" > "$QNXPORT_INNER" 2>&1 < /dev/null &
  qp=$!; qi=0
  while kill -0 $qp 2>/dev/null && [ $qi -lt 170 ]; do sleep 1; qi=$((qi+1)); done
  if kill -0 $qp 2>/dev/null; then
    for p in $(cat "$QNXPORT_INNER.pids" 2>/dev/null); do kill $p 2>/dev/null; done
    kill $qp 2>/dev/null; sleep 1; kill -KILL $qp 2>/dev/null
    cat "$QNXPORT_INNER"; echo "  FAIL watchdog: still running after 170 s -- stopped"
    echo "FAIL ${0##*/} (watchdog)"; rm -f "$QNXPORT_INNER" "$QNXPORT_INNER.pids"; exit 1
  fi
  wait $qp; rc=$?; cat "$QNXPORT_INNER"; rm -f "$QNXPORT_INNER" "$QNXPORT_INNER.pids"; exit $rc
fi
N=scdoc
echo "== $N =="
fail=0
ok() { echo "  ok   $1"; }; bad() { echo "  FAIL $1"; fail=$((fail+1)); }; info() { echo "  info $1"; }
has() { awk -v p="$1" 'index($0, p) {f=1} END {exit !f}'; }
L=/usr/local; [ -d "$L/bin" ] || L=/data/oss/usr/local
D=$(cd "$(dirname "$0")" && pwd)   # helpers next to this test
T=$(mktemp -d /tmp/qnxport-$N.XXXXXX) && cd "$T" || { echo "FAIL $N (no temp dir)"; exit 1; }
# Whatever the test starts stops with it, on every exit path (track PID;
# qstop_hook for anything else); the outer shell above kills them on a hang.
QP=$QNXPORT_INNER.pids; : > "$QP"
track() { echo "$1" >> "$QP"; }
qstop_hook() { :; }
stopall() {
  qstop_hook 2>/dev/null
  for p in $(cat "$QP" 2>/dev/null); do kill "$p" 2>/dev/null; done
  : > "$QP"; [ -n "$T" ] && [ -d "$T" ] && { cd /; rm -rf "$T"; }
}
trap stopall EXIT
trap 'exit 143' TERM
to() { if command -v timeout >/dev/null 2>&1; then timeout "$@"; else shift; "$@"; fi; }
SC=$L/bin/scdoc
cat > t.scd <<'EOS'
qnxdemo(1)

# NAME

qnxdemo - a demonstration page for the scdoc test

# SYNOPSIS

*qnxdemo* [_options_] <file>

# DESCRIPTION

Text with *bold*, _underlined_ and \*escaped\* words.

- first item
- second item
	- nested item

. one
. two

```
literal  block
  kept as is
```

[[ *Option*
:< *Meaning*
|  -v
:  verbose
|  -q
:  quiet

# SEE ALSO

*scdoc*(5)
EOS
SOURCE_DATE_EPOCH=0 "$SC" < t.scd > t.1 2> err.txt; rc=$?
c=$(cksum < t.1 | awk '{print $1, $2}')
[ $rc -eq 0 ] && [ "$c" = "1671456797 770" ] && ok "t.1 identical to the build machine's scdoc output (cksum $c)" || { bad "render (rc $rc): cksum $c $(cat err.txt)"; cat t.1; }
head -n 1 t.1 | has "Generated by scdoc 1.11.3" && ok "generated by scdoc 1.11.3" || bad "header: $(head -n 1 t.1)"
grep -q '^\.TH "qnxdemo" "1" "1970-01-01"$' t.1 && ok ".TH with the SOURCE_DATE_EPOCH date" || bad ".TH"
grep -q '^Text with \\fBbold\\fR, \\fIunderlined\\fR and \*escaped\* words\.\\&$' t.1 && ok "bold, underline, escaped asterisks" || bad "inline formatting"
grep -q '^\.TS$' t.1 && grep -q '^\\fBMeaning\\fR$' t.1 && ok "table (.TS) with bold header cells" || bad "table"
grep -q '^literal  block$' t.1 && ok "literal block kept as is" || bad "literal block"
r=$(printf 'nohead\n' | "$SC" 2>&1 >/dev/null); rc=$?
[ $rc -eq 1 ] && [ "$r" = "Error at 2:0: Expected manual section" ] && ok "no manual section: error at 2:0, exit 1" || bad "nohead (rc $rc): $r"
stopall
[ $fail -eq 0 ] && { echo "PASS $N"; exit 0; }
echo "FAIL $N ($fail check(s) failed)"; exit 1
